import argparse
import json

PARAMETER_TYPE_NAMES = {
    "angle": "Angle",
    "length": "Length",
    "length-none": "LengthNone",
    "length-percentage": "LengthPercentage",
    "number": "Number",
    "number-percentage": "NumberPercentage",
}


def write_generated_file(transforms_data: dict, output_path: str) -> None:
    with open(output_path, "w", encoding="utf-8") as output_file:
        output_file.write(
            """/*
 * Copyright (c) 2026-present, the Ladybird developers.
 *
 * SPDX-License-Identifier: BSD-2-Clause
 */

// Automatically generated by Meta/Generators/generate_libweb_css_transform_functions_rust.py.
// Do not edit.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum TransformFunctionParameterType {
    Angle,
    Length,
    LengthNone,
    LengthPercentage,
    Number,
    NumberPercentage,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct TransformFunctionParameter {
    pub(crate) parameter_type: TransformFunctionParameterType,
    pub(crate) required: bool,
}

"""
        )

        for name, value in transforms_data.items():
            constant_name = name.upper()
            output_file.write(f"const {constant_name}_PARAMETERS: &[TransformFunctionParameter] = &[\n")
            for parameter in value["parameters"]:
                parameter_type_name = parameter["type"].strip("<>")
                if parameter_type_name not in PARAMETER_TYPE_NAMES:
                    raise ValueError(f"Unknown transform function parameter type: {parameter_type_name}")
                parameter_type = PARAMETER_TYPE_NAMES[parameter_type_name]
                required = "true" if parameter["required"] else "false"
                output_file.write(
                    f"    TransformFunctionParameter {{ parameter_type: TransformFunctionParameterType::{parameter_type}, required: {required} }},\n"
                )
            output_file.write("];\n\n")

        output_file.write(
            """pub(crate) fn transform_function_parameters_from_name(name: &str) -> Option<&'static [TransformFunctionParameter]> {
"""
        )
        for name in transforms_data:
            output_file.write(f"""    if name.eq_ignore_ascii_case("{name}") {{
        return Some({name.upper()}_PARAMETERS);
    }}
""")
        output_file.write(
            """
    None
}
"""
        )


def main():
    parser = argparse.ArgumentParser(description="Generate Rust CSS transform function metadata", add_help=False)
    parser.add_argument("--help", action="help", help="Show this help message and exit")
    parser.add_argument("-j", "--json", required=True, help="Path to the JSON file to read from")
    parser.add_argument("-o", "--output", required=True, help="Path to the Rust file to generate")
    args = parser.parse_args()

    with open(args.json, "r", encoding="utf-8") as input_file:
        transforms_data = json.load(input_file)

    write_generated_file(transforms_data, args.output)


if __name__ == "__main__":
    main()
